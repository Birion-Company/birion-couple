  SELECT 1 FROM "categories" c WHERE c."householdId" = h."id" AND lower(translate(c.name, 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucaaaaaeeeeiiiiooooouuuuc')) IN ('compras', 'compras gerais')
